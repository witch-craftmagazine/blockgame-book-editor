function createGlyph(char: string, name: string, category: GlyphCategory): GlyphItem {
  const code = char.codePointAt(0) ?? 0;
  return {
    char,
    name,
    category,
    codepoint: `U+${code.toString(16).toUpperCase().padStart(4, '0')}`,
    isSmp: code > 0xFFFF,
  };
}

